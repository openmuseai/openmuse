final Uint8List _gbkCodeUnits = base64Decode(_gbkBase64);

String decodeGbk(Uint8List bytes) {
  final output = <int>[];
  for (var i = 0; i < bytes.length; i++) {
    final lead = bytes[i];
    if (lead < 0x80) {
      output.add(lead);
      continue;
    }
    if (lead < 0x81 || lead > 0xfe || i + 1 >= bytes.length) {
      throw const FormatException('invalid GBK lead byte');
    }
    final trail = bytes[++i];
    if (trail < 0x40 || trail > 0xfe || trail == 0x7f) {
      throw const FormatException('invalid GBK trail byte');
    }
    final trailIndex = trail < 0x7f ? trail - 0x40 : trail - 0x41;
    final index = ((lead - 0x81) * 190 + trailIndex) * 2;
    final codepoint = _gbkCodeUnits[index] | (_gbkCodeUnits[index + 1] << 8);
    if (codepoint == 0) {
      throw const FormatException('unmapped GBK pair');
    }
    output.add(codepoint);
  }
  return String.fromCharCodes(output);
}

bool looksLikeGbk(Uint8List bytes) {
  if (bytes.length < 2 || bytes.length.isOdd) return false;
  final lead = bytes[0], trail = bytes[1];
  return lead >= 0xb0 && lead <= 0xf7 && trail >= 0xa1 && trail <= 0xfe ||
      lead >= 0x81 && lead <= 0xfe && trail >= 0x40 && trail <= 0xfe;
}
