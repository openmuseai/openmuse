import {readFileSync} from 'node:fs';
import {generateKeyPairSync,createPublicKey} from 'node:crypto';
import {ControlStore} from '../src/store.mjs';
const registry=JSON.parse(readFileSync(new URL('../../../packages/openmuse_i18n/assets/catalog.json',import.meta.url)));
const bundle=JSON.parse(readFileSync(new URL('../../../packages/openmuse_runtime_config/assets/deployments/global-us.json',import.meta.url)));
const {privateKey}=generateKeyPairSync('ed25519'),origin='https://config.example.test',now='2026-10-30T00:00:00Z';
bundle.bootstrap.discoveryUrls=[origin+'/v1/runtime/scopes/dynamic/active.jws'];
bundle.bootstrap.publicKeys={test:createPublicKey(privateKey).export({format:'jwk'}).x};
bundle.bootstrap.allowedResourceOrigins=[origin];
const store=new ControlStore({database:':memory:',privateKey,kid:'test',publicOrigin:origin,clock:()=>new Date(now)});
store.createScope('dynamic',bundle,'admin');
const snapshot=structuredClone(bundle.snapshot);
snapshot.compatibility.requiredCapabilities.push('messages.dynamic.v1','settings.v1');
snapshot.settings={features:{'plugins.market.enabled':false,'updates.prompts.enabled':false},parameters:{'runtime.refreshIntervalSeconds':60,'plugins.example.limit':17}};
snapshot.localization.enabledLocales.push('fr');
snapshot.localization.localeCatalog=[{tag:'fr',label:'Français',formatLocale:'fr',direction:'ltr',aliases:['fr-FR'],uiKey:'fr'}];
const body={snapshot,note:'Downloadable French fixture',packs:[{schemaVersion:1,sourceRevision:registry.metadata.sourceRevision,locale:'fr',namespace:'common',messages:{'common.save':'Enregistrer','common.cancel':'Annuler'}}]};
let draft=store.createDraft('dynamic',body,'editor');draft=store.submit(draft.id,draft.version,'editor');store.approve(draft.id,draft.hash,'reviewer');
const release=store.publish(draft.id,draft.hash,store.scope('dynamic').revision,'publisher',600);
console.log(JSON.stringify({bundle,now,jws:release.jws,snapshot:release.snapshot,resources:Object.fromEntries(release.snapshot.resources.map(r=>[r.url,store.resource(r.sha256).toString('base64')]))}));
store.close();
