import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:math';

/// Public DSH generation tools. Native session transport stays inside this plugin.
final class DshGeneration {
  DshGeneration({
    required this.endpoint,
    required this.token,
    required this.mount,
    required this.ready,
    required this.openSession,
  });
  final Uri? Function() endpoint;
  final String token;
  final String? Function() mount;
  final Future<void> Function() ready;
  final void Function(String) openSession;
  final _tasks = <String, _Task>{};
  final _conversations =
      <String, ({String caller, String mount, String session})>{};
  String _id() => List.generate(
    24,
    (_) => Random.secure().nextInt(256).toRadixString(16).padLeft(2, '0'),
  ).join();
  static Map<String, Object?> _tool(
    String name,
    String description,
    Map<String, Object?> properties,
    List<String> required,
  ) => {
    'name': name,
    'description': description,
    'inputSchema': {
      'type': 'object',
      'properties': properties,
      'required': required,
      'additionalProperties': false,
    },
  };
  static final tools = [
    _tool(
      'dsh_generate',
      'DSH generation v1. Submit text to a visible DSH conversation. Returns an owned task; poll status until completed, failed or cancelled. The response is generated by the configured model.',
      {
        'text': {'type': 'string', 'minLength': 1, 'maxLength': 32000},
        'conversationRef': {'type': 'string'},
      },
      ['text'],
    ),
    _tool(
      'dsh_generation_status',
      'Read only a task owned by this caller.',
      {
        'taskRef': {'type': 'string'},
      },
      ['taskRef'],
    ),
    _tool(
      'dsh_generation_cancel',
      'Cancel only the generation owned by this caller.',
      {
        'taskRef': {'type': 'string'},
      },
      ['taskRef'],
    ),
  ];
  Map<String, Object?> _result(Object value) => {
    'content': [
      {'type': 'text', 'text': jsonEncode(value)},
    ],
    'structuredContent': value,
  };
  Future<Map<String, Object?>> call(
    String caller,
    String name,
    Map<String, Object?> args,
  ) async {
    if (name == 'dsh_generate') {
      final text = args['text'];
      if (text is! String ||
          text.trim().isEmpty ||
          text.length > 32000 ||
          args.keys.any((k) => !{'text', 'conversationRef'}.contains(k)))
        throw StateError('INVALID_INPUT');
      if (_tasks.values.any((t) => t.caller == caller && t.state == 'running'))
        throw StateError('GENERATION_ALREADY_RUNNING');
      final currentMount = mount();
      if (currentMount == null) throw StateError('WORKSPACE_UNAVAILABLE');
      final ref = args['conversationRef'];
      if (ref != null &&
          (ref is! String ||
              _conversations[ref]?.caller != caller ||
              _conversations[ref]?.mount != currentMount))
        throw StateError('CONVERSATION_SCOPE_MISMATCH');
      if (_tasks.length >= 128) {
        _tasks.removeWhere((_, task) => task.state != 'running');
        if (_tasks.length >= 128)
          throw StateError('GENERATION_BUDGET_EXCEEDED');
      }
      final task = _Task(_id(), caller, currentMount, ref as String? ?? _id());
      _tasks[task.ref] = task;
      unawaited(_start(task, text));
      return _result(task.json());
    }
    final task = _tasks[args['taskRef']];
    if (task == null || task.caller != caller)
      throw StateError('TASK_SCOPE_MISMATCH');
    if (name == 'dsh_generation_cancel')
      await _cancel(task);
    else if (name != 'dsh_generation_status')
      throw StateError('TOOL_UNAVAILABLE');
    return _result(task.json());
  }

  Future<Map<String, dynamic>> _post(
    String path,
    Map<String, Object?> body,
  ) async {
    final client = HttpClient()..connectionTimeout = const Duration(seconds: 5);
    try {
      final request = await client.postUrl(endpoint()!.resolve(path));
      request.headers
        ..contentType = ContentType.json
        ..set('x-openmuse-bridge-token', token);
      request.write(jsonEncode(body));
      final response = await request.close().timeout(
        const Duration(seconds: 30),
      );
      final value = jsonDecode(await utf8.decoder.bind(response).join());
      if (response.statusCode != 200 || value is! Map)
        throw StateError('DSH_REQUEST_REJECTED');
      return Map<String, dynamic>.from(value);
    } finally {
      client.close(force: true);
    }
  }

  Future<void> _start(_Task task, String text) async {
    try {
      await ready();
      if (task.state != 'running') return;
      var conversation = _conversations[task.conversation];
      if (conversation == null) {
        final catalog = await _post('/openmuse-bridge/workspaces', {
          'mounts': [task.mount],
        });
        final workspace = (catalog['items'] as List)
            .whereType<Map>()
            .firstWhere((w) => w['path'] == task.mount);
        final created = await _post('/openmuse-native/v1/session/create', {
          'workspaceId': workspace['workspaceId'],
        });
        final session = created['sessionId'];
        if (session is! String) throw StateError('DSH_SESSION_INVALID');
        conversation = (
          caller: task.caller,
          mount: task.mount,
          session: session,
        );
        if (task.state != 'running') return;
        _conversations[task.conversation] = conversation;
      }
      task.session = conversation.session;
      openSession(conversation.session);
      final snapshot = Completer<void>();
      task.client = HttpClient()
        ..connectionTimeout = const Duration(seconds: 5);
      final request = await task.client!.getUrl(
        endpoint()!.resolve(
          '/openmuse-native/v1/session/follow?sessionId=${Uri.encodeQueryComponent(conversation.session)}',
        ),
      );
      request.headers.set('x-openmuse-bridge-token', token);
      task.phase = 'connecting_stream';
      final response = await request.close().timeout(
        const Duration(seconds: 15),
      );
      task.phase = 'waiting_snapshot';
      if (response.statusCode != 200)
        throw StateError('DSH_STREAM_UNAVAILABLE');
      task.subscription = response
          .transform(utf8.decoder)
          .transform(const LineSplitter())
          .listen(
            (line) {
              if (!line.startsWith('data: ')) return;
              try {
                final frame = jsonDecode(line.substring(6)) as Map;
                if (frame['type'] == 'snapshot') {
                  if (!snapshot.isCompleted) snapshot.complete();
                  return;
                }
                if (task.state != 'running' ||
                    !task.submitted ||
                    frame['type'] != 'event')
                  return;
                final event = frame['event'] as Map,
                    data = event['data'] as Map? ?? {};
                if (event['type'] == 'turn/start') task.started = true;
                if (!task.started) return;
                if (event['type'] == 'assistant/message') {
                  final message = data['message'] as Map?;
                  final text = (message?['content'] as List? ?? [])
                      .whereType<Map>()
                      .where((c) => c['type'] == 'text')
                      .map((c) => c['text'] as String? ?? '')
                      .join('\n');
                  if (text.isNotEmpty) task.output.add(text);
                }
                if (event['type'] == 'turn/end') {
                  final reason = data['reason'] as Map?;
                  task.state =
                      reason?['kind'] == 'completed' && task.output.isNotEmpty
                      ? 'completed'
                      : 'failed';
                  if (task.state == 'failed')
                    task.error = 'DSH_GENERATION_INCOMPLETE';
                  unawaited(_closeStream(task));
                }
              } catch (_) {
                task.error = 'DSH_STREAM_INVALID';
                task.state = 'failed';
                if (!snapshot.isCompleted)
                  snapshot.completeError(StateError('DSH_STREAM_INVALID'));
                unawaited(_closeStream(task));
              }
            },
            onError: (Object error) {
              if (task.state == 'running') {
                task.state = 'failed';
                task.error = 'DSH_STREAM_DISCONNECTED';
              }
              if (!snapshot.isCompleted)
                snapshot.completeError(StateError('DSH_STREAM_DISCONNECTED'));
            },
            onDone: () {
              if (task.state == 'running') {
                task.state = 'failed';
                task.error = 'DSH_STREAM_CLOSED';
              }
              if (!snapshot.isCompleted)
                snapshot.completeError(StateError('DSH_STREAM_CLOSED'));
            },
          );
      await snapshot.future.timeout(const Duration(seconds: 20));
      if (task.state != 'running') {
        await _closeStream(task);
        return;
      }
      task.phase = 'submitting_prompt';
      task.submitted = true;
      final receipt = await _post('/openmuse-native/v1/session/prompt', {
        'sessionId': task.session,
        'requestId': 'plugin-${task.ref}',
        'mode': 'queue',
        'content': [
          {'type': 'text', 'text': text},
        ],
      });
      if (receipt['accepted'] != true)
        throw StateError('DSH_PROMPT_NOT_ACCEPTED');
      if (task.state == 'cancelled') {
        await _post('/openmuse-native/v1/session/cancel', {
          'sessionId': task.session,
        });
        return;
      }
      if (task.state == 'running') {
        task.phase = 'generating';
        task.timer = Timer(
          const Duration(minutes: 3),
          () => unawaited(_cancel(task, timeout: true)),
        );
      }
    } catch (error) {
      if (task.state == 'running') {
        task.state = 'failed';
        task.error =
            error is StateError && RegExp(r'^[A-Z_]+$').hasMatch(error.message)
            ? error.message
            : 'DSH_GENERATION_FAILED_${error.runtimeType}';
      }
      await _closeStream(task);
    }
  }

  Future<void> _closeStream(_Task task) async {
    task.timer?.cancel();
    task.timer = null;
    await task.subscription?.cancel();
    task.subscription = null;
    task.client?.close(force: true);
    task.client = null;
  }

  Future<void> _cancel(_Task task, {bool timeout = false}) async {
    if (task.state != 'running') return;
    task.state = timeout ? 'failed' : 'cancelled';
    if (timeout) task.error = 'GENERATION_TIMEOUT';
    try {
      if (task.submitted && task.session != null)
        await _post('/openmuse-native/v1/session/cancel', {
          'sessionId': task.session,
        });
    } catch (_) {
      task.state = 'failed';
      task.error = 'GENERATION_CANCEL_UNCONFIRMED';
    } finally {
      await _closeStream(task);
    }
  }

  Future<void> disposeCaller(String caller) async {
    for (final task
        in _tasks.values.where((t) => t.caller == caller).toList()) {
      await _cancel(task);
      _tasks.remove(task.ref);
    }
    _conversations.removeWhere((_, value) => value.caller == caller);
  }

  Future<void> close() async {
    for (final caller in _tasks.values.map((t) => t.caller).toSet()) {
      await disposeCaller(caller);
    }
  }
}

final class _Task {
  _Task(this.ref, this.caller, this.mount, this.conversation);
  final String ref, caller, mount, conversation;
  String state = 'running';
  String phase = 'preparing';
  String? session, error;
  bool submitted = false, started = false;
  final output = <String>[];
  HttpClient? client;
  StreamSubscription<String>? subscription;
  Timer? timer;
  Map<String, Object?> json() => {
    'taskRef': ref,
    'conversationRef': conversation,
    'status': state,
    'phase': phase,
    'text': output.join('\n'),
    if (error != null) 'error': error,
  };
}
